-- Feature Flag Platform: initial schema.
-- Written in the common subset of PostgreSQL and H2 so the same migrations run in tests and prod.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE projects (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key VARCHAR(64)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_projects_key UNIQUE (project_key)
);

CREATE TABLE environments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    env_key      VARCHAR(64)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    color        VARCHAR(7)   NOT NULL,
    sort_order   INT          NOT NULL,
    -- Only a SHA-256 hash of the SDK key is stored; the raw key is shown once on creation/rotation.
    sdk_key_hash VARCHAR(64)  NOT NULL,
    sdk_key_hint VARCHAR(16)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_environments_project_key UNIQUE (project_id, env_key),
    CONSTRAINT uk_environments_sdk_key UNIQUE (sdk_key_hash)
);

CREATE TABLE feature_flags (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    flag_key    VARCHAR(64)   NOT NULL,
    name        VARCHAR(100)  NOT NULL,
    description VARCHAR(1000),
    flag_type   VARCHAR(16)   NOT NULL,
    variations  TEXT          NOT NULL,
    salt        VARCHAR(32)   NOT NULL,
    -- Variations used to initialise targeting in newly created environments.
    default_on_variation  INT NOT NULL,
    default_off_variation INT NOT NULL,
    temporary   BOOLEAN       NOT NULL,
    archived    BOOLEAN       NOT NULL,
    version     BIGINT        NOT NULL,
    created_by  VARCHAR(255),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_flags_project_key UNIQUE (project_id, flag_key)
);

CREATE TABLE flag_tags (
    flag_id BIGINT      NOT NULL REFERENCES feature_flags (id) ON DELETE CASCADE,
    tag     VARCHAR(64) NOT NULL,
    PRIMARY KEY (flag_id, tag)
);
CREATE INDEX idx_flag_tags_tag ON flag_tags (tag);

CREATE TABLE flag_configs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flag_id        BIGINT  NOT NULL REFERENCES feature_flags (id) ON DELETE CASCADE,
    environment_id BIGINT  NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    enabled        BOOLEAN NOT NULL,
    targeting      TEXT    NOT NULL,
    version        BIGINT  NOT NULL,
    updated_by     VARCHAR(255),
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_flag_configs_flag_env UNIQUE (flag_id, environment_id)
);
CREATE INDEX idx_flag_configs_environment ON flag_configs (environment_id);

CREATE TABLE segments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    segment_key VARCHAR(64)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    included    TEXT         NOT NULL,
    excluded    TEXT         NOT NULL,
    rules       TEXT         NOT NULL,
    version     BIGINT       NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_segments_project_key UNIQUE (project_id, segment_key)
);

-- Append-only audit trail. Deliberately no FK to projects so history survives deletions.
CREATE TABLE audit_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key     VARCHAR(64),
    environment_key VARCHAR(64),
    resource_type   VARCHAR(32)  NOT NULL,
    resource_key    VARCHAR(64)  NOT NULL,
    action          VARCHAR(32)  NOT NULL,
    actor           VARCHAR(255) NOT NULL,
    summary         VARCHAR(500) NOT NULL,
    before_state    TEXT,
    after_state     TEXT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_audit_project_created ON audit_log (project_key, created_at DESC);
CREATE INDEX idx_audit_resource ON audit_log (resource_type, resource_key);
