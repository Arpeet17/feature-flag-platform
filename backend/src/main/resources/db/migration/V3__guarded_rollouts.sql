-- Guarded progressive rollouts: a flag variation ramped through percentage steps while a
-- guardrail metric is watched; the rollout advances, holds or rolls back automatically.
CREATE TABLE rollouts (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id           BIGINT       NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    environment_id       BIGINT       NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    flag_key             VARCHAR(64)  NOT NULL,
    treatment_variation  INT          NOT NULL,
    control_variation    INT          NOT NULL,
    steps                VARCHAR(200) NOT NULL,   -- JSON array of percentages, e.g. [1,5,25,50,100]
    step_interval_secs   INT          NOT NULL,
    min_users_per_step   INT          NOT NULL,
    guardrail_event_key  VARCHAR(64),
    current_step         INT          NOT NULL,
    status               VARCHAR(16)  NOT NULL,
    step_started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    next_check_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Version of the flag's targeting this rollout last wrote; any other version means a human
    -- edited the flag mid-rollout, so the rollout pauses instead of overwriting their change.
    expected_config_version BIGINT    NOT NULL,
    last_decision        VARCHAR(500),
    created_by           VARCHAR(255),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    version              BIGINT       NOT NULL
);
CREATE INDEX idx_rollouts_due ON rollouts (status, next_check_at);
CREATE INDEX idx_rollouts_flag ON rollouts (environment_id, flag_key);

CREATE TABLE rollout_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rollout_id   BIGINT       NOT NULL REFERENCES rollouts (id) ON DELETE CASCADE,
    at           TIMESTAMP WITH TIME ZONE NOT NULL,
    step         INT          NOT NULL,
    percentage   INT          NOT NULL,
    action       VARCHAR(16)  NOT NULL,
    detail       VARCHAR(1000) NOT NULL
);
CREATE INDEX idx_rollout_history ON rollout_history (rollout_id, at);
