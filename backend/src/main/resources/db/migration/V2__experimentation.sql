-- Experimentation: exposures (who saw which variation), metric events, experiment definitions.

-- One row per user per flag: the FIRST exposure wins (intention-to-treat). If a user's variation
-- later changes (e.g. a rollout is edited mid-experiment), the analysis keeps their original arm.
CREATE TABLE exposures (
    environment_id BIGINT       NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    flag_key       VARCHAR(64)  NOT NULL,
    context_key    VARCHAR(256) NOT NULL,
    variation      INT          NOT NULL,
    -- True only if the variation was assigned by a percentage rollout. Users served by a targeting
    -- rule were not randomized and must be excluded from analysis, or they bias the comparison.
    randomized     BOOLEAN      NOT NULL,
    exposed_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (environment_id, flag_key, context_key)
);
CREATE INDEX idx_exposures_flag_time ON exposures (environment_id, flag_key, exposed_at);

CREATE TABLE metric_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    environment_id BIGINT       NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    event_key      VARCHAR(64)  NOT NULL,
    context_key    VARCHAR(256) NOT NULL,
    numeric_value  DOUBLE PRECISION,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_metric_events_lookup ON metric_events (environment_id, event_key, context_key, occurred_at);

CREATE TABLE experiments (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id         BIGINT        NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    environment_id     BIGINT        NOT NULL REFERENCES environments (id) ON DELETE CASCADE,
    experiment_key     VARCHAR(64)   NOT NULL,
    name               VARCHAR(100)  NOT NULL,
    hypothesis         VARCHAR(1000),
    flag_key           VARCHAR(64)   NOT NULL,
    metric_event_key   VARCHAR(64)   NOT NULL,
    metric_type        VARCHAR(16)   NOT NULL,
    higher_is_better   BOOLEAN       NOT NULL,
    control_variation  INT           NOT NULL,
    status             VARCHAR(16)   NOT NULL,
    started_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    stopped_at         TIMESTAMP WITH TIME ZONE,
    created_by         VARCHAR(255),
    version            BIGINT        NOT NULL,
    CONSTRAINT uk_experiments_project_key UNIQUE (project_id, experiment_key)
);
