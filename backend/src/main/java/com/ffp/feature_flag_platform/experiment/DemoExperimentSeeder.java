package com.ffp.feature_flag_platform.experiment;

import com.ffp.feature_flag_platform.environment.Environment;
import com.ffp.feature_flag_platform.evaluation.model.EvaluationContext;
import com.ffp.feature_flag_platform.evaluation.model.EvaluationResult;
import com.ffp.feature_flag_platform.evaluation.runtime.EvaluationService;
import com.ffp.feature_flag_platform.experiment.EventStore.Exposure;
import com.ffp.feature_flag_platform.experiment.EventStore.MetricEvent;
import com.ffp.feature_flag_platform.experiment.stats.ExperimentAnalyzer.MetricType;
import com.ffp.feature_flag_platform.project.Project;
import org.springframework.stereotype.Component;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Random;

/**
 * Synthetic experiment traffic for the demo project, generated by assigning users with the
 * real evaluation engine and drawing outcomes from known true rates. The second experiment
 * deliberately loses some treatment exposures (a simulated logging bug) so the dashboard shows
 * what a sample ratio mismatch looks like.
 */
@Component
public class DemoExperimentSeeder {

    private final ExperimentRepository experiments;
    private final EventStore events;
    private final EvaluationService evaluation;
    private final Clock clock;

    public DemoExperimentSeeder(ExperimentRepository experiments, EventStore events, EvaluationService evaluation, Clock clock) {
        this.experiments = experiments;
        this.events = events;
        this.evaluation = evaluation;
        this.clock = clock;
    }

    public void seed(Project project, Environment production) {
        Instant now = clock.instant();
        Instant start = now.minus(Duration.ofDays(6));
        Random random = new Random(2024);

        experiments.save(new Experiment(project, production, "search-ranking", "Search ranking A/B/C",
                "Hybrid ranking increases search click-through. (Synthetic demo data: true rates 10% / 11% / 12.8%.)",
                "search-algorithm", "search-click", MetricType.CONVERSION, true, 0, start, "system"));
        simulate(production.getId(), "search-algorithm", "search-click", 15_000, start, now, random,
                Map.of(0, 0.10, 1, 0.11, 2, 0.128), Map.of(), false);

        experiments.save(new Experiment(project, production, "checkout-revenue", "New checkout: revenue per user",
                "The one-page checkout raises revenue per user. (Synthetic demo data with a planted logging bug: "
                        + "15% of new-checkout exposures are lost, which the sample ratio check catches.)",
                "new-checkout", "revenue", MetricType.MEAN, true, 1, start, "system"));
        simulate(production.getId(), "new-checkout", "revenue", 40_000, start, now, random,
                Map.of(0, 0.32, 1, 0.30), Map.of(0, 0.15), true);
    }

    /**
     * @param conversionRate true probability of the metric event per variation
     * @param lossRate       probability an exposure of that variation is never logged (bug simulation)
     */
    private void simulate(long environmentId, String flagKey, String eventKey, int users, Instant from, Instant to, Random random,
                          Map<Integer, Double> conversionRate, Map<Integer, Double> lossRate, boolean revenue) {
        List<Exposure> exposures = new ArrayList<>();
        List<MetricEvent> metrics = new ArrayList<>();
        long span = Duration.between(from, to).toMillis();
        for (int i = 0; i < users; i++) {
            String user = "demo-" + flagKey + "-" + i;
            EvaluationResult r = evaluation.evaluateOne(environmentId, flagKey,
                    new EvaluationContext(user, Map.of("email", "user" + i + "@example.com")));
            if (r.variationIndex() == null) continue;
            int variation = r.variationIndex();
            Instant exposedAt = from.plusMillis((long) (random.nextDouble() * span * 0.9));
            boolean logged = random.nextDouble() >= lossRate.getOrDefault(variation, 0.0);
            if (logged) {
                exposures.add(new Exposure(environmentId, flagKey, user, variation, Boolean.TRUE.equals(r.reason().inRollout()), exposedAt));
            }
            if (random.nextDouble() < conversionRate.getOrDefault(variation, 0.0)) {
                Instant at = exposedAt.plusMillis((long) (random.nextDouble() * Math.min(span * 0.1, 3_600_000)));
                Double value = revenue ? Math.round((25 + random.nextGaussian() * 8 + (variation == 0 ? 3 : 0)) * 100) / 100.0 : null;
                metrics.add(new MetricEvent(environmentId, eventKey, user, value, at));
            }
        }
        events.saveExposures(exposures);
        events.saveMetricEvents(metrics);
    }
}
